import { useEffect, useState } from "react";
import { client, errMsg } from "../../api/client";
import { Button, Card, EmptyState, ErrorBanner, LoadingState, PageHeader, Table } from "../../components/ui";
import { StatCard } from "../../components/cards";
import { useToast } from "../../components/Toast";
import { fmtMoney } from "./constants";

const EXPORTS = [
  { type: "orders", label: "Orders" },
  { type: "transactions", label: "Transactions" },
  { type: "users", label: "Users" },
];

export default function SuperAdminReports() {
  const toast = useToast();
  const [rows, setRows] = useState(null);
  const [analytics, setAnalytics] = useState(null);
  const [error, setError] = useState("");
  const [exporting, setExporting] = useState("");

  async function load() {
    setError("");
    try {
      const [cmp, an] = await Promise.all([
        client.get("/super/analytics/compare"),
        client.get("/admin/analytics"),
      ]);
      setRows(cmp.data.universities || []);
      setAnalytics(an.data);
    } catch (err) {
      setError(errMsg(err, "Could not load reports"));
      setRows([]);
    }
  }

  useEffect(() => {
    load();
  }, []);

  async function exportCsv(type) {
    setExporting(type);
    setError("");
    try {
      const { data } = await client.get("/admin/reports/export", { params: { type }, responseType: "blob" });
      const url = URL.createObjectURL(data);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${type}.csv`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
      toast.success(`${type} export downloaded.`);
    } catch (err) {
      setError(errMsg(err, "Could not export the report"));
    } finally {
      setExporting("");
    }
  }

  const totals = (rows || []).reduce(
    (acc, r) => {
      acc.users += Number(r.users) || 0;
      acc.stores += Number(r.stores) || 0;
      acc.orders += Number(r.orders) || 0;
      acc.gmv += Number(r.gmv) || 0;
      acc.commission += Number(r.commission_earned) || 0;
      return acc;
    },
    { users: 0, stores: 0, orders: 0, gmv: 0, commission: 0 }
  );

  return (
    <div>
      <PageHeader
        title="Reports"
        subtitle="Per-campus KPIs and CSV exports scoped to the whole platform."
      />

      <ErrorBanner message={error} onClose={() => setError("")} />

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        <StatCard icon="user" label="Users" value={totals.users} />
        <StatCard icon="store" label="Stores" value={totals.stores} />
        <StatCard icon="orders" label="Orders" value={totals.orders} />
        <StatCard icon="wallet" label="GMV (completed)" value={fmtMoney(totals.gmv)} />
      </div>

      <Card className="mt-6 p-5">
        <h2 className="text-sm font-semibold text-ink">Export data</h2>
        <p className="mt-0.5 text-xs text-muted">CSV files include every campus. Generated by the reporting API.</p>
        <div className="mt-3 flex flex-wrap gap-2">
          {EXPORTS.map((e) => (
            <Button key={e.type} variant="outline" size="sm" loading={exporting === e.type} onClick={() => exportCsv(e.type)}>
              Export {e.label}
            </Button>
          ))}
        </div>
      </Card>

      <Card className="mt-6 p-5">
        <div className="flex items-center justify-between gap-3">
          <div>
            <h2 className="text-sm font-semibold text-ink">Per-campus comparison</h2>
            <p className="mt-0.5 text-xs text-muted">Commission earned is the platform's cut per campus.</p>
          </div>
          <span className="text-xs text-muted">Commission total: {fmtMoney(totals.commission)}</span>
        </div>
      </Card>

      {rows === null ? (
        <div className="mt-4">
          <LoadingState label="Loading report data…" />
        </div>
      ) : rows.length === 0 ? (
        <div className="mt-4">
          <EmptyState icon="reports" title="No data to report" subtitle="No campuses have been created yet." />
        </div>
      ) : (
        <div className="mt-4">
          <Table
            head={["Campus", "Status", "Users", "Stores", "Orders", "GMV", "Commission", "Events", "Tickets", "Listings", "Rentals"]}
          >
            {rows.map((r) => (
              <tr key={r.id} className="text-slate-700">
                <td className="px-4 py-3 font-medium text-ink">{r.name}</td>
                <td className="px-4 py-3 text-muted">{r.status}</td>
                <td className="px-4 py-3">{r.users}</td>
                <td className="px-4 py-3">{r.stores}</td>
                <td className="px-4 py-3">{r.orders}</td>
                <td className="px-4 py-3">{fmtMoney(r.gmv)}</td>
                <td className="px-4 py-3">{fmtMoney(r.commission_earned)}</td>
                <td className="px-4 py-3">{r.published_events}</td>
                <td className="px-4 py-3">{r.tickets_sold}</td>
                <td className="px-4 py-3">{r.active_listings}</td>
                <td className="px-4 py-3">{r.rental_bookings}</td>
              </tr>
            ))}
          </Table>
          {analytics?.orders && (
            <p className="mt-3 text-xs text-muted">
              Platform completed order revenue: {fmtMoney(analytics.orders.completedRevenue)} across {analytics.orders.count} orders.
            </p>
          )}
        </div>
      )}
    </div>
  );
}
